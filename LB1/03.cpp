/**
 * @file 03.cpp
 * @brief Реализация «безопасного массива» SafeArray с контролем границ.
 *
 * Демонстрирует:
 *  - структуру SafeArray, инкапсулирующую указатель и размер;
 *  - безопасный доступ к элементам через getElement() с защитой от выхода за границы;
 *  - использование функции доступа слева от знака равенства (возврат ссылки);
 *  - печать массива без его изменения (const-ссылка);
 *  - изменение размера массива с сохранением данных и выводом удалённых элементов.
 */

#include <iostream>

/**
 * @brief Структура «безопасный массив».
 *
 * Хранит указатель на динамический массив и его размер.
 * Не владеет памятью в смысле RAII — освобождение выполняется вручную.
 */
struct SafeArray {
    int* data;  ///< Указатель на динамический массив элементов
    int size;   ///< Текущее количество элементов
};

/**
 * @brief Создаёт SafeArray заданного размера.
 *
 * Выделяет память под массив через `new int[size]{}` (инициализация нулями).
 * Если size <= 0, массив не выделяется, а указатель data становится nullptr.
 *
 * @param size Желаемое количество элементов.
 * @return Структура SafeArray по значению.
 *
 * @note Память должна быть освобождена через `delete[] arr.data`.
 */
SafeArray createArray(int size) {
    SafeArray arr;
    arr.size = size;
    if (size > 0) {
        arr.data = new int[size]{};     /// Выделение памяти с инициализацией нулями
    } else {
        arr.data = nullptr;             /// Пустой массив
    }
    return arr;
}

/**
 * @brief Безопасный доступ к элементу массива по индексу.
 *
 * Если индекс выходит за границы [0; arr.size), выводит сообщение об ошибке
 * в std::cerr и возвращает ссылку на статическую переменную-заглушку.
 * Это позволяет использовать функцию слева от знака равенства даже при
 * некорректном индексе — без падения программы и без порчи основного массива.
 *
 * @param arr   Ссылка на структуру SafeArray.
 * @param index Индекс запрашиваемого элемента.
 * @return Ссылка на элемент arr.data[index] или на статическую заглушку.
 *
 * @code
 * getElement(myArr, 2) = 999; // корректная запись
 * getElement(myArr, 100) = 1; // ошибка, запись уйдёт в заглушку
 * @endcode
 */
int& getElement(SafeArray& arr, int index) {
    static int dummy = 0;   ///< Заглушка для некорректных индексов

    if (index < 0 || index >= arr.size) {
        std::cerr << "Ошибка: индекс " << index
                  << " вне диапазона [0, " << arr.size - 1 << "].\n";
        return dummy;
    }
    return arr.data[index];
}

/**
 * @brief Печатает содержимое SafeArray.
 *
 * Принимает константную ссылку, так как печать не изменяет данные.
 * Если массив пуст, выводит «(пусто)».
 *
 * @param arr Ссылка на константный SafeArray.
 */
void printSafe(const SafeArray& arr) {
    std::cout << "Массив (size = " << arr.size << "): ";
    if (arr.size == 0 || arr.data == nullptr) {
        std::cout << "(пусто)\n";
        return;
    }
    for (int i = 0; i < arr.size; ++i) {
        std::cout << arr.data[i] << " ";
    }
    std::cout << "\n";
}

/**
 * @brief Изменяет размер SafeArray с текущего на M.
 *
 * Поведение:
 *  - Если M < oldSize: элементы с индексами [M; oldSize) выводятся на экран
 *    как «удалённые», затем отбрасываются.
 *  - Если M > oldSize: новые элементы инициализируются нулями.
 *  - Данные, попадающие в новый диапазон, копируются.
 *
 * Старая память корректно освобождается, указатель перенаправляется на новый массив.
 *
 * @param arr Ссылка на SafeArray, размер которого нужно изменить.
 * @param M   Новый размер массива (может быть 0).
 */
void reSizeArray(SafeArray& arr, int M) {
    int oldSize = arr.size;

    // Вывод удаляемых элементов при уменьшении
    if (M < oldSize) {
        std::cout << "Удалённые элементы: ";
        for (int i = M; i < oldSize; ++i) {
            std::cout << arr.data[i] << " ";
        }
        std::cout << "\n";
    }

    // Выделение нового массива (с инициализацией нулями)
    int* newData = nullptr;
    if (M > 0) {
        newData = new int[M]{};
    }

    // Копирование сохраняемых элементов
    int copyCount = (M < oldSize) ? M : oldSize;
    for (int i = 0; i < copyCount; ++i) {
        newData[i] = arr.data[i];
    }

    // Сообщение о добавленных элементах
    if (M > oldSize) {
        std::cout << "Добавлено " << (M - oldSize)
                  << " новых элементов, инициализированных нулями.\n";
    }

    // Освобождение старой памяти и обновление структуры
    delete[] arr.data;
    arr.data = newData;
    arr.size = M;
}

/**
 * @brief Точка входа. Демонстрирует работу SafeArray.
 *
 * Сценарий:
 *  1. Создание массива из 5 элементов.
 *  2. Заполнение значениями 10, 20, 30, 40, 50.
 *  3. Запись через getElement(myArr, 2) = 999.
 *  4. Проверка выхода за границы (индексы 100 и -1) — безопасно.
 *  5. Уменьшение размера с 5 до 3 (вывод удалённых).
 *  6. Увеличение размера с 3 до 6 (новые элементы = 0).
 *  7. Освобождение памяти и обнуление указателя.
 *
 * @return 0 — успешное завершение.
 */
int main() {
    SafeArray myArr = createArray(5);

    // Заполнение массива значениями 10, 20, 30, 40, 50
    for (int i = 0; i < myArr.size; ++i) {
        getElement(myArr, i) = (i + 1) * 10;
    }

    std::cout << "Исходный ";
    printSafe(myArr);

    // Демонстрация использования getElement слева от знака равенства
    getElement(myArr, 2) = 999;
    std::cout << "После getElement(myArr, 2) = 999: ";
    printSafe(myArr);

    // Проверка безопасного поведения при выходе за границы
    std::cout << "\nПопытка доступа по некорректному индексу:\n";
    getElement(myArr, 100) = 12345;     ///< Запись уйдёт в заглушку
    std::cout << "После некорректного доступа: ";
    printSafe(myArr);

    getElement(myArr, -1) = -777;       ///< Отрицательный индекс — тоже безопасно
    std::cout << "После отрицательного индекса: ";
    printSafe(myArr);

    // Уменьшение размера: 5 -> 3
    std::cout << "\n--- Уменьшение размера с 5 до 3 ---\n";
    reSizeArray(myArr, 3);
    printSafe(myArr);

    // Увеличение размера: 3 -> 6
    std::cout << "\n--- Увеличение размера с 3 до 6 ---\n";
    reSizeArray(myArr, 6);
    printSafe(myArr);

    // Освобождение памяти
    delete[] myArr.data;
    myArr.data = nullptr;
    myArr.size = 0;

    return 0;
}