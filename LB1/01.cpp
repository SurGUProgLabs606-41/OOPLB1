/**
 * @file 01.cpp
 * @brief Операции над статическим массивом целых чисел.
 *
 * Демонстрирует работу с массивом фиксированного размера через ссылки:
 *  - заполнение случайными числами;
 *  - вывод элементов;
 *  - обмен двух элементов по индексам;
 *  - умножение всех элементов на 2.
 *
 * Использование ссылок на массив `int (&arr)[10]` позволяет сохранять
 * информацию о размере и избегать затухания массива до указателя.
 */

#include <iostream>
#include <cstdlib> ///Для rand - для генерации случайных чисел
#include <ctime>

/**
 * @brief Заполняет массив случайными числами в диапазоне [1; 100].
 *
 * Использует rand(), поэтому перед вызовом желательно инициализировать
 * генератор через srand().
 *
 * @param arr Ссылка на массив из 10 элементов.
 *
 * @see srand, rand
 */
void fillArray(int (&arr)[10]) {
    for (int i = 0; i < 10; ++i) {
        arr[i] = rand() % 100 + 1;
    }
}

/**
 * @brief Выводит элементы массива в одну строку через пробел.
 *
 * Принимает константную ссылку, так как вывод не изменяет массив.
 * Использует range-based for для безопасного перебора.
 *
 * @param arr Константная ссылка на массив из 10 элементов.
 */
void printArray(const int (&arr)[10]) {
    for (const auto& element : arr) {
        std::cout << element << " ";
    }
    std::cout << std::endl;
}

/**
 * @brief Меняет местами два элемента массива по заданным индексам.
 *
 * Классический обмен через временную переменную.
 * Индексы должны находиться в диапазоне [0; 9].
 *
 * @param arr    Ссылка на массив из 10 элементов.
 * @param index1 Индекс первого элемента.
 * @param index2 Индекс второго элемента.
 *
 * @warning При выходе индексов за границы массива поведение не определено.
 */
void swapElements(int (&arr)[10], int index1, int index2) {
    int temp = arr[index1];
    arr[index1] = arr[index2];
    arr[index2] = temp;
}

/**
 * @brief Умножает каждый элемент массива на 2.
 *
 * Использует range-based for со ссылкой, чтобы изменить элементы «на месте».
 *
 * @param arr Ссылка на массив из 10 элементов.
 */
void multiplyByTwo(int (&arr)[10]) {
    for (int& x : arr) {
        x *= 2;
    }
}

/**
 * @brief Точка входа в программу.
 *
 * Демонстрирует работу с массивом целых чисел:
 * инициализирует генератор случайных чисел, заполняет массив,
 * выводит его, меняет местами элементы по заданным индексам
 * и умножает все элементы на 2.
 *
 * @return 0 при успешном завершении программы.
 */
int main() {
    srand(static_cast<unsigned int>(time(nullptr)));   /// Инициализация генератора, потому что time выдаёт разные значения

    int myArray[10];                                    /// Статический массив из 10 элементов

    fillArray(myArray);
    std::cout << "Исходный массив: ";
    printArray(myArray);

    swapElements(myArray, 2, 7);
    std::cout << "После swap (индексы 2 и 7): ";
    printArray(myArray);

    multiplyByTwo(myArray);
    std::cout << "После умножения на 2: ";
    printArray(myArray);

    return 0;
}