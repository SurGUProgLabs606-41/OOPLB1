/**
 * @file 02.cpp
 * @brief Обработка одномерного динамического массива.
 *
 * Демонстрирует:
 *  - работу с new/delete для одномерного динамического массива;
 *  - передачу указателя по ссылке (int*&), чтобы изменить сам указатель;
 *  - усечение массива до первого отрицательного элемента без утечек памяти;
 *  - защиту от «болтающихся указателей» (dangling pointers) после delete.
 */

#include <iostream>

/**
 * @brief Обрабатывает массив: усекает его до первого отрицательного элемента.
 *
 * Алгоритм:
 *  1. Ищет первый отрицательный элемент.
 *  2. Если такого нет — массив не изменяется, выводится сообщение.
 *  3. Если найден — создаётся новый массив размером negIndex,
 *     в него копируются все элементы до отрицательного,
 *     старая память освобождается, а указатель arr перенаправляется на новый массив.
 *
 * Указатель передаётся по ссылке (int*&), чтобы изменить сам указатель
 * в вызывающем коде. Размер size также передаётся по ссылке, так как он
 * меняется после усечения.
 *
 * @param arr  Ссылка на указатель на массив. После вызова может указывать
 *             на новый массив (если найден отрицательный элемент).
 * @param size Ссылка на размер массива. Обновляется до нового размера.
 *
 * @note Если отрицательный элемент первый (negIndex == 0), создаётся
 *       массив нулевого размера, а size становится равным 0.
 *
 * @warning Перед вызовом arr должен указывать на память, выделенную через
 *          new[] (не nullptr и не статический массив).
 */
void process(int*& arr, int& size) {
    // Поиск первого отрицательного элемента
    int negIndex = -1;
    for (int i = 0; i < size; ++i) {
        if (arr[i] < 0) {
            negIndex = i;
            break;
        }
    }

    // Если отрицательного элемента нет — массив не меняем
    if (negIndex == -1) {
        std::cout << "Отрицательных элементов не найдено. Массив не изменён.\n";
        return;
    }

    // Создание нового массива размером negIndex
    int newSize = negIndex;
    int* newArr = new int[newSize]{};   /// Новый массив с инициализацией нулями

    // Копирование элементов до отрицательного
    for (int i = 0; i < newSize; ++i) {
        newArr[i] = arr[i];
    }

    // Освобождение старой памяти и обновление указателя/размера
    delete[] arr;
    arr = newArr;
    size = newSize;

    std::cout << "Первый отрицательный элемент найден по индексу " << negIndex
              << ". Массив усечён до " << newSize << " элементов.\n";
}

/**
 * @brief Точка входа. Демонстрирует обработку динамического массива.
 *
 * Сценарий:
 *  1. Пользователь вводит размер N и N элементов.
 *  2. Массив выводится на экран.
 *  3. Вызывается process() — массив усекается до первого отрицательного.
 *  4. Выводится результат (или сообщение о пустом массиве).
 *  5. Память освобождается, указатель обнуляется.
 *  6. Демонстрируется безопасное поведение: проверка на nullptr
 *     перед разыменованием предотвращает Segmentation Fault.
 *
 * @return 0 — успешное завершение или некорректный размер.
 */
int main() {
    int N;
    std::cout << "Введите размер массива N: ";
    std::cin >> N;

    if (N <= 0) {
        std::cout << "Размер должен быть положительным.\n";
        return 0;
    }

    // Выделение памяти под массив с инициализацией нулями
    int* arr = new int[N]{};

    // Ввод элементов
    std::cout << "Введите " << N << " элементов массива:\n";
    for (int i = 0; i < N; ++i) {
        std::cin >> arr[i];
    }

    // Вывод исходного массива
    std::cout << "Исходный массив: ";
    for (int i = 0; i < N; ++i) {
        std::cout << arr[i] << " ";
    }
    std::cout << "\n";

    // Обработка массива (усечение до первого отрицательного)
    int size = N;
    process(arr, size);

    // Вывод результата (с защитой от пустого массива)
    if (size == 0) {
        std::cout << "Результат: массив пуст.\n";
    } else {
        std::cout << "Результат: ";
        for (int i = 0; i < size; ++i) {
            std::cout << arr[i] << " ";
        }
        std::cout << "\n";
    }

    // Освобождение памяти и обнуление указателя
    delete[] arr;
    arr = nullptr;

    // Демонстрация безопасного поведения после delete
    std::cout << "\nДемонстрация безопасного поведения после delete:\n";
    if (arr == nullptr) {
        std::cout << "Указатель arr == nullptr. Разыменование пропущено "
                     "(защита от Segmentation Fault).\n"
                     "nullptr - это нулевая константа, которая ни на что не указывает.";
    } else {
        std::cout << "Значение по указателю: " << *arr << "\n";
    }

    return 0;
}